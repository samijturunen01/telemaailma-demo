/**
 * Recreates the authentic SolarWorks logo as a clean SVG.
 *
 * Source: source-assets/solarworks-logo-original.png (1984×992, from the
 * company's former solarworks.fi website). The PNG has a grey drop shadow, so
 * only the amber artwork pixels are isolated before tracing. The arc and the
 * lettering are emitted as separate paths so they can be animated
 * independently. Enclosed counters (O, R, A) are preserved by potrace's
 * even-odd output.
 *
 * Usage: node scripts/trace-logo.mjs
 */
import sharp from 'sharp'
import potrace from 'potrace'
import fs from 'node:fs/promises'

const SRC = 'source-assets/solarworks-logo-original.png'
const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
const { width, height } = info

const mask = Buffer.alloc(width * height)
let rSum = 0
let gSum = 0
let bSum = 0
let n = 0
for (let i = 0; i < width * height; i++) {
  const r = data[i * 4]
  const g = data[i * 4 + 1]
  const b = data[i * 4 + 2]
  const a = data[i * 4 + 3]
  const amber = a > 110 && r > 170 && g > 100 && b < 120 && r - b > 110
  mask[i] = amber ? 0 : 255
  if (amber && a > 250) {
    rSum += r
    gSum += g
    bSum += b
    n++
  }
}
const hex = (v) => Math.round(v).toString(16).padStart(2, '0')
const amberHex = `#${hex(rSum / n)}${hex(gSum / n)}${hex(bSum / n)}`
console.log('Sampled amber:', amberHex, `(${n} px)`)

const maskPng = await sharp(mask, { raw: { width, height, channels: 1 } }).png().toBuffer()

const svg = await new Promise((resolve, reject) =>
  potrace.trace(
    maskPng,
    { threshold: 128, turdSize: 20, optTolerance: 0.25, color: amberHex, background: 'transparent' },
    (err, out) => (err ? reject(err) : resolve(out)),
  ),
)

const d = svg.match(/ d="([^"]+)"/)[1]
// Split into sub-paths and classify by vertical position.
const subs = d.match(/M[^M]+/g)
const bbox = (p) => {
  const nums = p.match(/-?\d+(\.\d+)?/g).map(Number)
  const xs = nums.filter((_, i) => i % 2 === 0)
  const ys = nums.filter((_, i) => i % 2 === 1)
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) }
}
const arc = []
const letters = []
let all = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity }
for (const s of subs) {
  const b = bbox(s)
  all = {
    x0: Math.min(all.x0, b.x0),
    y0: Math.min(all.y0, b.y0),
    x1: Math.max(all.x1, b.x1),
    y1: Math.max(all.y1, b.y1),
  }
  ;(b.y1 < 500 ? arc : letters).push(s.trim())
}
console.log(`Sub-paths: arc=${arc.length}, letters=${letters.length}`, all)

const pad = 4
const vb = [all.x0 - pad, all.y0 - pad, all.x1 - all.x0 + pad * 2, all.y1 - all.y0 + pad * 2].map(
  (v) => Math.round(v),
)
const out = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}" role="img" aria-label="SolarWorks">
  <path id="sw-arc" fill="${amberHex}" d="${arc.join(' ')}"/>
  <path id="sw-letters" fill="${amberHex}" fill-rule="evenodd" d="${letters.join(' ')}"/>
</svg>
`
await fs.writeFile('public/brand/solarworks-logo.svg', out)
await fs.writeFile(
  'src/data/solarworksLogo.ts',
  `// Generated by scripts/trace-logo.mjs from the authentic SolarWorks logo. Do not edit by hand.
export const SOLARWORKS_AMBER = '${amberHex}'
export const SOLARWORKS_VIEWBOX = '${vb.join(' ')}'
export const SOLARWORKS_ARC_PATH = '${arc.join(' ')}'
export const SOLARWORKS_LETTERS_PATH = '${letters.join(' ')}'
`,
)
console.log('Wrote public/brand/solarworks-logo.svg and src/data/solarworksLogo.ts')
